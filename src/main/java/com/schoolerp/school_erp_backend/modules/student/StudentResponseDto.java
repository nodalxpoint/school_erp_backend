package com.schoolerp.school_erp_backend.modules.student;

import java.time.LocalDate;
import java.util.UUID;

import com.schoolerp.school_erp_backend.modules.attendance.AttendanceSummaryDto;

public class StudentResponseDto {

    private UUID id;
    private String firstName;
    private String lastName;
    private String admissionNo;
    private String gender;
    private LocalDate dob;
    private LocalDate admissionDate;

    // Enrollment details
    private UUID classId;
    private String className;
    private UUID sectionId;
    private String sectionName;
    private UUID academicSessionId;
    private String rollNo;
    
    private AttendanceSummaryDto attendance;

    public StudentResponseDto() {
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public String getAdmissionNo() {
        return admissionNo;
    }

    public void setAdmissionNo(String admissionNo) {
        this.admissionNo = admissionNo;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public LocalDate getDob() {
        return dob;
    }

    public void setDob(LocalDate dob) {
        this.dob = dob;
    }

    public LocalDate getAdmissionDate() {
        return admissionDate;
    }

    public void setAdmissionDate(LocalDate admissionDate) {
        this.admissionDate = admissionDate;
    }

    public UUID getClassId() {
        return classId;
    }

    public void setClassId(UUID classId) {
        this.classId = classId;
    }

    public String getClassName() {
        return className;
    }

    public void setClassName(String className) {
        this.className = className;
    }

    public UUID getSectionId() {
        return sectionId;
    }

    public void setSectionId(UUID sectionId) {
        this.sectionId = sectionId;
    }

    public String getSectionName() {
        return sectionName;
    }

    public void setSectionName(String sectionName) {
        this.sectionName = sectionName;
    }

    public UUID getAcademicSessionId() {
        return academicSessionId;
    }

    public void setAcademicSessionId(UUID academicSessionId) {
        this.academicSessionId = academicSessionId;
    }

    public String getRollNo() {
        return rollNo;
    }

    public void setRollNo(String rollNo) {
        this.rollNo = rollNo;
    }

	public AttendanceSummaryDto getAttendance() {
		return attendance;
	}

	public void setAttendance(AttendanceSummaryDto attendance) {
		this.attendance = attendance;
	}
    
    

}
